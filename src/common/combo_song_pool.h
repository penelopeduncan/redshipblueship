#pragma once
/**
 * @file combo_song_pool.h
 * @brief THE PAIR'S ONE SONGS SETTING (#1542 D2; OoTMM `songs`, "Controls where
 *        songs can be obtained, in both games"). Game-header-free.
 *
 * A paired OoT + MM world is one game (one-game semantics), and OoTMM has one
 * songs setting for both games (packages/core/src/settings/data.ts, `songs`).
 * Operator ruling 2026-11-10 (D2): Majora's Mask's Shuffle Songs follows Ocarina
 * of Time's. The player sets SoH's own Shuffle Songs row; MM's row is shown
 * read-only with COMBO_SONGS_SET_BY_OOT_REASON (combo_settings_view.h).
 *
 * THE MAPPING (Combo_PairSongsMmValue), OoT's four values onto MM's three:
 *
 *   OoT Off (0)             -> MM Vanilla (2)         OoTMM has no Off; both games vanilla
 *   OoT Song Locations (1)  -> MM Song Locations (1)  OoTMM songLocations (the default)
 *   OoT Dungeon Rewards (2) -> MM Song Locations (1)  OoTMM has none; MM keeps its own
 *                                                     song checks (design decision 1)
 *   OoT Anywhere (3)        -> MM Anywhere (0)        OoTMM anywhere
 *
 * A value outside OoT's four maps as OoT's shipped default (Song Locations): a
 * frozen OoT option never holds one (SoH's option clamps), and the pane preview
 * is the only reader that could see a hand-edited key.
 *
 * WHERE THE VALUE COMES FROM (one-game semantics: decided once, at creation).
 * MM's half is generated by the completion (OoT_PairedGen_CompleteWorld), after
 * OoT's Playthrough_Init froze the pair, and in a test process after the
 * file-create invalidation too. MM's paired resolution therefore reads, in order:
 *
 *   1. THE CAPTURE: OoT's finalized RSK_SHUFFLE_SONGS, recorded by
 *      Playthrough_Init at the freeze (just before the MM profile stamp, after
 *      both early-return gates) and consumed by the completion, which clears it
 *      on every exit. It is NOT saved and NOT a gComboCtx field: after
 *      completion the value is MM's frozen RANDO_SAVE_OPTIONS and OoT's own
 *      settings string, so it is derivable. Context_InvalidateSessionState keeps
 *      it under RSBS_SEED_STAMP_KEEP (a test-mode completion runs after that
 *      invalidation) and clears it under DROP. Playthrough_Init's rollback puts
 *      the prior value back (Combo_PairSongsSnapshot / Combo_PairSongsRestore).
 *   2. Otherwise (the pane's preview before any Generate) OoT's key,
 *      RSBS_OOT_SHUFFLE_SONGS_CVAR, with OoT's shipped default.
 *
 * MM's own key is never read for a paired world. Every compare of a frozen MM
 * profile (the arrival gate, the load classification, the restore's after-check)
 * tries each of MM's three values: the row is a pure function of OoT's setting,
 * which OoT's own identity already guards, so the MM compare must not depend on
 * it, and every world frozen before #1542 (MM's value from MM's own key) keeps
 * loading. A frozen world's shown value is the one its stamp reproduces.
 */

